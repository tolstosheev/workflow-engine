# Строки, которые не должны появляться в пользовательском тексте.
USER_VISIBLE_SUSPECT = ("Исчерпани проходов", "Показать нельзя сюже", "обрращения")

WORD = re.compile("|".join(re.escape(word) for word in SUSPECT))


def _text_files() -> list[Path]:
    return [
        path
        for path in ROOT.rglob("*")
        if path.is_file()
        and path.suffix in TEXT_SUFFIXES
        and not any(part in SKIP_DIRS for part in path.parts)
        and "test_repository_text" not in path.name
    ]


def test_repository_comments_are_not_corrupted() -> None:
    offenders: list[str] = []
    for path in _text_files():
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if WORD.search(line):
                offenders.append(f"{path.relative_to(ROOT)}:{number}")
    assert offenders == [], "повреждённый текст: " + ", ".join(offenders)


def test_a_second_line_cannot_catch_readable_but_wrong_words() -> None:
    """Ограничение стража записано, чтобы его не искали заново.

    Порча при правке через консоль даёт три класса, и ловятся два:

    - буквы превратились в вопросительные знаки или знак замены — ловится
      поиском по трём знакам подряд;
    - слово перестало существовать, но осталось читаемым («небьзя») — ловится
      словарём, то есть только если случай уже кто-то нашёл глазами;
    - остальное — нечитаемое, но грамматически возможное — не ловится ничем.

    Автоматическая вторая линия была попробована: слово, встретившееся один раз,
    сравнивалось с лексиконом, собранным из самого дерева. Из 1576 таких слов
    уцелели почти все, потому что русская морфология даёт каждой форме слова
    отдельное написание, а редкое в дереве слово — обычное. Детектор без
    словаря языка не отличает порчу от склонения, и подставить его вместо
    словаря значило бы заменить точные срабатывания шумом.
    """
    # Утверждение не проверяет текст дерева, а фиксирует границы приёма:
    # заменить словарь эвристикой нельзя, и это должно быть видно в коде.
    assert SUSPECT, "словарь порчи не должен опустеть"


def test_no_run_of_question_marks_replaces_russian_letters() -> None:
    # Словарь выше ловит только те случаи, которые уже нашли глазами: новая
    # порча его проходит, потому что её нет в списке. Здесь ловится сам класс —
    # буквы, превратившиеся в вопросительные знаки или в знак замены.
    #
    # Три знака подряд в этом проекте не встречаются: тернарный оператор пишется
    # с пробелами, ленивые квантификаторы регулярных выражений — с одним
    # знаком, связка `??` — с двумя.
    run_of_marks = re.compile(r"\?{3,}|\uFFFD")

    offenders: list[str] = []
    for path in _text_files():
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if run_of_marks.search(line):
                offenders.append(f"{path.relative_to(ROOT).as_posix()}:{number}")
    assert offenders == [], "текст потерял буквы: " + ", ".join(offenders)


def test_user_visible_text_is_intact() -> None:
    # Пользователь читает эти строки, а не разработчик: испорченная подпись
    # видна сразу и стоит дороже, чем испорченный комментарий.
    offenders: list[str] = []
    for path in ROOT.joinpath("frontend/src").rglob("*"):
        if path.suffix not in {".ts", ".tsx"}:
            continue
        text = path.read_text(encoding="utf-8")
        if any(word in text for word in USER_VISIBLE_SUSPECT):
            offenders.append(path.relative_to(ROOT).as_posix())
    assert offenders == [], "испорченные надписи: " + ", ".join(offenders)
