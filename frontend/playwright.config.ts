import { defineConfig, devices } from '@playwright/test'

/**
 * Сквозные проверки стенда.
 *
 * Тесты идут против настоящего стенда: compose поднимает БД, движок и интерфейс,
 * и проверяется ровно то, что увидит человек. Отдельный стенд ради этого не
 * поднимается — дублировать compose ради ещё одного прогона незачем.
 *
 * Адрес берётся из окружения: локально стенд может стоять не на тех портах,
 * что в compose (у соседних проектов заняты 8000 и 5173), а в CI — на штатных.
 */
const baseURL = process.env.E2E_BASE_URL ?? 'http://localhost:5173'

export default defineConfig({
  testDir: './e2e',
  // Параллельно не гоняем: процессы на стенде общие, и два прогона вмешались бы
  // в инъекции друг друга. Секунды дешевле, чем разбор «тест упал, потому что
  // чужой прогон сломал состояние».
  workers: 1,
  // Ожидание заложено под живой стенд: процесс идёт через воркеров, а не через
  // один запрос. Таймаут, подобранный под конкретный запуск, хуже его отсутствия.
  timeout: 60_000,
  expect: { timeout: 15_000 },
  reporter: process.env.CI ? [['github'], ['list']] : 'list',
  use: {
    baseURL,
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
  },
  projects: [{ name: 'chromium', use: { ...devices['Desktop Chrome'] } }],
})
