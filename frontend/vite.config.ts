import { fileURLToPath } from 'node:url'

import { defineConfig } from 'vitest/config'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'

// Адрес бэкенда для прокси сервера разработки. Внутри docker-compose это
// сетевое имя `api`, и compose задаёт его литералом. Вне контейнера (локальный
// запуск vite на машине) сетевого имени нет, поэтому умолчание — хостовый адрес.
//
// Переменная одна, и это сделано намеренно: раньше адрес жил в VITE_API_URL,
// который попадал в браузер, а порт публикации жил в API_PORT. Настройка одной
// тянула за собой вторую, а рассинхрон проявлялся пустым списком без единой
// ошибки в консоли.
const API_URL = process.env.API_PROXY_TARGET ?? 'http://localhost:8000'

/**
 * Пути, которые прокси отдаёт бэкенду.
 *
 * Список явный, потому что «всё подряд» означало бы, что адрес опечатки в
 * клиенте тихо уезжает на бэкенд и получает 404 оттуда, а не от дев-сервера:
 * разница в том, чей это 404, и по ней дефект потом не находится.
 */
export const PROXIED_PATHS = ['/api', '/metrics'] as const

/**
 * Переход браузера на страницу и запрос данных — не одно и то же.
 *
 * Адрес метрик `/metrics` совпадает с маршрутом страницы состояния, и прокси
 * перехватывал оба: открыть «Состояние» было нельзя, вместо неё приходил
 * сырой текст экспозиции. Различить их можно по заголовку `Accept`:
 * навигация просит HTML, а запрос данных — звёздочку.
 *
 * Отдельно осторожно с текстом комментария: последовательность «звёздочка,
 * косая черта» внутри него закрывает комментарий, и дальше файл читается как
 * код. TypeScript такой файл принимает, esbuild — нет, поэтому дев-сервер
 * падал с ошибкой, которой не было видно на странице.
 */
function isPageNavigation(request: { headers: Record<string, unknown> }): boolean {
  const accept = String(request.headers.accept ?? '')
  return accept.includes('text/html')
}

export default defineConfig({
  plugins: [react(), tailwindcss()],
  resolve: {
    // Алиас дублирует paths из tsconfig.json: TypeScript резолвит импорты
    // сам, а Vite о них не знает.
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    // Браузер ходит в свой origin, и прокси отдаёт ему всё, что лежит на
    // бэкенде. Список не сводится к `/api`: метрики живут по `/metrics`, и
    // когда их убрали из прокси, страница состояния молча показывала нули —
    // 404 от дев-сервера разбирался как «метрик нет». Страж, который следит за
    // полнотой списка, живёт в `tests/unit/test_api_paths.py`.
    //
    // SSE через EventSource не умеет слать заголовки, поэтому CORS на бэкенде
    // настроен на конкретные origins — но через прокси он всё равно нужен для
    // прямых обращений из сквозных проверок и инструментов.
    proxy: Object.fromEntries(
      PROXIED_PATHS.map((path) => [
        path,
        {
          target: API_URL,
          changeOrigin: true,
          // Навигацию на `/metrics` отдаём приложению, а не бэкенду: страница
          // состояния живёт по тому же адресу.
          bypass: (request: { headers: Record<string, unknown> }) =>
            path === '/metrics' && isPageNavigation(request) ? '/index.html' : undefined,
        },
      ]),
    ),
  },
  test: {
    // Чистая логика проверяется без DOM, а компонентные тесты требуют
    // разметки: окружение jsdom включается по файлу-признаку `.tsx`,
    // чтобы логика оставалась быстрой.
    environment: 'node',
    include: ['src/**/*.test.ts', 'src/**/*.test.tsx'],
    // Пять секунд по умолчанию рассчитаны на чистую логику. Тест страницы под
    // инструментацией покрытия монтирует разметку, ждёт асинхронную загрузку
    // и разбирает её, и на пределе упирается в таймаут — падал файл проверок
    // определений, хотя ни один его тест не был медленным сам по себе.
    testTimeout: 15_000,
    coverage: {
      provider: 'v8',
      // Порог считает только то, что проверяется исполнением. Раньше страницы
      // и компоненты были исключены, потому что исполнять их было нечем: без
      // разметки они не выполнялись, и включение их в отчёт дало бы «100%
      // покрытие» на невыполненном коде. Теперь jsdom есть, список страниц
      // покрыт частично — и это уже настоящая цифра, а не выдуманная.
      include: ['src/lib/**', 'src/store/**', 'src/hooks/**', 'src/api/**', 'src/components/**', 'src/pages/**'],
      reporter: ['text'],
      // Порог держится на достигнутом, а не на завышенном. Он сдвинулся вниз
      // один раз — когда Vitest 4 переписал подсчёт V8 на анализ AST вместо
      // `v8-to-istanbul`, и прежние 93 % просто не учитывали часть строк. С
      // тех пор порог только рос: сначала до 90/80/91/92, затем, когда долг по
      // страницам и стору закрыт, до теперешних значений. Падение ниже порога
      // означает, что появился непокрытый участок, а не что кто-то сузил
      // include: под отчётом весь `src`.
      //
      // Остаток долга виден по каталогам: `pages` — 76 % веток, `store` — 78 %.
      // Там не исполняются второстепенные ветки отображения, а не пути, по
      // которым принимается решение.
      thresholds: {
        statements: 94,
        branches: 83,
        functions: 96,
        lines: 96,
      },
    },
  },
})
