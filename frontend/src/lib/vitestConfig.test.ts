// Стройная настройка проверок лежит рядом с исходниками, но `tsconfig`
// включает только `src`, а `vite.config.ts` тянет типы Node — импорт конфига
// из проверки ломал бы `npm run typecheck`. Поэтому конфиг читается как текст:
// проверяется ровно то, что написано в файле, и проверка не меняет то, что
// компилируется.

/**
 * Настройки прогона проверок.
 *
 * Число процессов пула ограничено намеренно. Без ограничения Vitest поднимает по
 * процессу на файл, и под нагрузкой часть исполнителей не отвечала на старте. Хуже
 * всего, как это выглядит: ошибка приходит «необработанной», а итоговая строка
 * сообщает о 213 пройденных тестах вместо 434 — прогон выглядит успешным, пока
 * половина файлов не выполнена.
 *
 * Страж стоит рядом с настройкой, а не в конце набора: упавший прогон заметен, а
 * вернувшийся лимит — нет.
 */

import { describe, expect, it } from 'vitest'

import raw from '../../vite.config.ts?raw'

/** Число после `maxWorkers` в настройках пула. */
function maxWorkers(): number | null {
  const found = /maxWorkers:\s*(\d+)/.exec(raw)
  return found ? Number(found[1]) : null
}

describe('настройка прогона проверок', () => {
  it('ограничивает число процессов пула', () => {
    const value = maxWorkers()

    // Процесс на файл на двенадцати ядрах — это двенадцать подъёмов сразу, и
    // на этой машине столько процессов не отвечали на старте вовремя.
    expect(value, 'maxWorkers не задан: пул поднимется без ограничения').not.toBeNull()
    expect(value as number).toBeGreaterThan(0)
    expect(value as number).toBeLessThanOrEqual(8)
  })

  it('оставляет тестам время на загрузку', () => {
    // Об этом напоминает падение файла проверок определений: страница
    // монтирует разметку, ждёт асинхронную загрузку и разбирает её.
    const found = /testTimeout:\s*([\d_]+)/.exec(raw)

    expect(found).not.toBeNull()
    expect(Number((found as RegExpExecArray)[1].replace(/_/g, ''))).toBeGreaterThanOrEqual(15_000)
  })
})