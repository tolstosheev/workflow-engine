/**
 * Порча правкой через консоль — заметная часть словаря уже была испорчена.
 *
 * Словарь запрещает «прогон» в надписях интерфейса: это слово тест-раннера, а
 * у шага на экране есть «выполнение шага». Замена сработала и по исходникам
 * целиком — комментарии и названия проверок тоже, где «прогон» означал именно
 * прогон. Итог читался как «счётчик снимается после загрузки, иначе утверждение
 * падало под нагрузкой полного выполнения шага» — слово на месте, смысл перепутан.
 *
 * Ловится этот класс грамматикой, а не словарём: «выполнение шага» — родительный
 * падеж, и никакое «выполнение шагаы» или «выполнение шага-призрак» русским языком
 * не является. Переставленные буквы так не ловятся, о чём и сказано в
 * `test_repository_text.py`: без словаря языка порча неотличима от слога.
 */

import { describe, expect, it } from 'vitest'

import { SOURCES } from './sources'

/**
 * Невозможные падежи: `выполнение` + `шага` + окончание или хвост через дефис.
 *
 * Границы слов в JavaScript работают по ASCII, и кириллица слово не считает:
 * обычный `\b` перед «выполнение» не срабатывал после кавычки, то есть проверка
 * молча пропускала именно то, ради чего написана. Поэтому граница задана
 * lookbehind'ом — буква рядом означает, что слово продолжается.
 */
const BROKEN = /(?<![а-яёa-z])выполнени[ея]\s+шага[а-я-]/giu

describe('порча словаря в исходниках', () => {
  it('не оставляет «выполнение шага» в невозможном падеже', () => {
    const found: string[] = []

    for (const [path, source] of Object.entries(SOURCES)) {
      // Сам файл проверки содержит примеры порчи в объяснении, и находит их сам.
      if (path.includes('brokenWording.test')) continue
      for (const match of source.matchAll(BROKEN)) {
        const line = source.slice(0, match.index).split('\n').length
        found.push(`${path}:${line}: ${match[0]}`)
      }
    }

    expect(found, 'замена «прогон» → «выполнение шага» задела комментарии').toEqual([])
  })

  it('читает файлы, а не пустой список', () => {
    // Страж, не открывший ничего, проходит «находок нет» всегда.
    expect(Object.keys(SOURCES).length).toBeGreaterThan(20)
  })
})